class View:
    def __init__(self):
        self.root = Node()

    def getSceneGraph(self):
        return self.root


class Control:
    dialog = None

    @classmethod
    def showDialog(cls, d):
        cls.dialog = d

    @classmethod
    def closeDialog(cls):
        cls.dialog = None

    @classmethod
    def activeDialog(cls):
        return cls.dialog is not None


def install():
    fc = types.ModuleType("FreeCAD")
    fc.Vector, fc.Placement, fc.Rotation, fc.Console = Vector, Placement, Rotation, Console
    fc.GuiUp = True
    fc.ActiveDocument = None
    groups = {}
    fc.ParamGet = lambda path: groups.setdefault(path, ParamGroup())
    sys.modules["FreeCAD"] = fc

    gui = types.ModuleType("FreeCADGui")
    gui.Control = Control
    gui.commands, gui.manipulators, gui.icon_paths = {}, [], []
    gui.addCommand = lambda n, c: gui.commands.__setitem__(n, c)
    gui.addWorkbenchManipulator = gui.manipulators.append
    gui.addIconPath = gui.icon_paths.append
    gui.ActiveDocument = types.SimpleNamespace(ActiveView=View())
    sys.modules["FreeCADGui"] = gui

    part = types.ModuleType("Part")
    part.Circle, part.ArcOfCircle, part.Line, part.makeCompound = Circle, ArcOfCircle, Line, makeCompound
    sys.modules["Part"] = part

    path = types.ModuleType("Path")
    base = types.ModuleType("Path.Base")
    util = types.ModuleType("Path.Base.Util")
    util.opProperty = lambda op, prop: getattr(op, prop, None)
    dressup = types.ModuleType("Path.Dressup")
    dutils = types.ModuleType("Path.Dressup.Utils")
    dutils.toolController = lambda op: getattr(op, "ToolController", None)
    path.Base, base.Util, path.Dressup, dressup.Utils = base, util, dressup, dutils
    sys.modules.update({"Path": path, "Path.Base": base, "Path.Base.Util": util,
                        "Path.Dressup": dressup, "Path.Dressup.Utils": dutils})
    ps = types.ModuleType("PathScripts")
    pu = types.ModuleType("PathScripts.PathUtils")
    pu.getPathWithPlacement = lambda op: op.Path
    ps.PathUtils = pu
    sys.modules.update({"PathScripts": ps, "PathScripts.PathUtils": pu})

    # CAM's machine models: MachineFactory.get_machine(name) from the .fcm fixtures
    mach = types.ModuleType("Machine")
    models = types.ModuleType("Machine.models")
    mm = types.ModuleType("Machine.models.machine")

    class MachineFactory:
        files = {}

        @classmethod
        def get_machine(cls, name):
            import json
            path = cls.files.get(name.lower())
            if path is None:
                raise FileNotFoundError(name)
            with open(path) as f:
                data = json.load(f)["machine"]
            axes = {}
            for n, a in data["axes"].items():
                if a.get("type") == "rotary":
                    o, d = a["joint"]
                    axes[n] = types.SimpleNamespace(rotation_vector=Vector(*d), joint_origin=list(o),
                                                    min_limit=a["limits"]["min"], max_limit=a["limits"]["max"],
                                                    sequence=a.get("sequence", 0), allow_flip=a.get("allow_flip"))
            return types.SimpleNamespace(name=data["name"], rotary_axes=axes)

    MachineFactory.list_configuration_files = classmethod(lambda cls: list(cls.files.items()))
    mm.MachineFactory = MachineFactory
    mach.models, models.machine = models, mm
    sys.modules.update({"Machine": mach, "Machine.models": models, "Machine.models.machine": mm})

    pivy = types.ModuleType("pivy")
    pivy.coin = make_coin()
    sys.modules.update({"pivy": pivy, "pivy.coin": pivy.coin})

    install_pyside_shim()
    return fc, gui


def install_pyside_shim():
    """FreeCAD's PySide shim on top of PySide6, if installed (returns False otherwise)."""
    try:
        import PySide6.QtCore
        import PySide6.QtGui  # noqa: F401
        import PySide6.QtWidgets
    except ImportError:
        return False
    shim = types.ModuleType("PySide")
    qtgui = types.ModuleType("PySide.QtGui")
    # same content as FreeCAD's generated Ext/PySide/QtGui.py
    exec("from PySide6.QtGui import *\nfrom PySide6.QtWidgets import *\n", qtgui.__dict__)
    shim.QtCore, shim.QtGui, shim.QtWidgets = PySide6.QtCore, qtgui, PySide6.QtWidgets
    sys.modules.update({"PySide": shim, "PySide.QtCore": PySide6.QtCore, "PySide.QtGui": qtgui,
                        "PySide.QtWidgets": PySide6.QtWidgets})
    return True
