"""
Stand-ins for the FreeCAD modules the addon imports, for headless tests.

They implement only what the addon calls, with the behaviour documented in
FreeCAD main (checked: Part TopoShape.slice(dir, d) is the plane dir.p = d,
Edge.discretize(Deflection=...), Shape.tessellate(tol), the PySide shim
generated by SetupShibokenAndPyside.cmake). Shapes are backed by section
fixtures taken from the sample Job, not by OCC, so these tests check the
addon's own logic, not FreeCAD's.

install() puts the stubs into sys.modules; call it before importing the GUI.
"""

import sys
import types


# ------------------------------------------------------------------- FreeCAD
class Vector:
    def __init__(self, x=0.0, y=0.0, z=0.0):
        self.x, self.y, self.z = float(x), float(y), float(z)


class Rotation:
    def __init__(self):
        self.Angle = 0.0
        self.Q = (0.0, 0.0, 0.0, 1.0)


class Placement:
    def __init__(self, base=None, rotation=None):
        self.Rotation = rotation or Rotation()
        self.Base = base or Vector()


class BoundBox:
    def __init__(self, xmin, ymin, zmin, xmax, ymax, zmax):
        self.XMin, self.YMin, self.ZMin, self.XMax, self.YMax, self.ZMax = xmin, ymin, zmin, xmax, ymax, zmax


class ParamGroup:
    def __init__(self):
        self.d = {}

    def _get(self, k, default):
        return self.d.get(k, default)

    GetBool = GetInt = GetFloat = GetString = _get

    def _set(self, k, v):
        self.d[k] = v

    SetBool = SetInt = SetFloat = SetString = _set


class Console:
    messages = []

    @classmethod
    def PrintError(cls, s):
        cls.messages.append(("error", s))

    @classmethod
    def PrintWarning(cls, s):
        cls.messages.append(("warning", s))

    @classmethod
    def PrintMessage(cls, s):
        cls.messages.append(("message", s))

    @classmethod
    def PrintLog(cls, s):
        cls.messages.append(("log", s))


# ---------------------------------------------------------------------- Part
class Circle:
    def __init__(self, centre, radius):
        self.Center = Vector(centre[0], 0.0, centre[1])
        self.Radius = radius


class ArcOfCircle:
    pass


class Line:
    pass


class Edge:
    def __init__(self, d, y):
        self._pts = d["points"]
        self._y = y
        self.Curve = Circle(d["centre"], d["radius"]) if d.get("kind") == "arc" else Line()

    def discretize(self, Deflection=None, **kw):
        assert Deflection is not None
        return [Vector(x, self._y, z) for x, z in self._pts]


class Wire:
    def __init__(self, edges):
        self.Edges = edges


class Shape:
    """A solid known only by its XZ section edges (at Y = section_y)."""

    def __init__(self, section_edges, bbox, section_y=0.0, mesh=None, sections=None, placement_y=0.0):
        """
        section_edges: the section at Y = section_y; or sections: a list of
        ((y_min, y_max), edges), the section anywhere in that Y range (e.g.
        an insert and the holder above it). bbox, section_y and the ranges
        are the raw geometry's; placement_y is a Y offset in the shape's
        Placement (as Part, BoundBox and slice see the placed shape).
        """
        self.section_edges = section_edges
        self.raw_bbox = bbox
        self.section_y = section_y
        self.sections = sections
        self.Placement = Placement(Vector(0.0, placement_y, 0.0))
        self.mesh = mesh
        self.slices = []

    @property
    def BoundBox(self):
        b, dy = self.raw_bbox, self.Placement.Base.y
        return BoundBox(b.XMin, b.YMin + dy, b.ZMin, b.XMax, b.YMax + dy, b.ZMax)

    def isNull(self):
        return False

    def copy(self):
        return Shape(self.section_edges, self.raw_bbox, self.section_y, self.mesh, self.sections,
                     self.Placement.Base.y)

    def slice(self, direction, d):
        assert (direction.x, direction.y, direction.z) == (0, 1, 0)
        self.slices.append(d)
        d -= self.Placement.Base.y          # in the raw geometry
        if self.sections is not None:
            for (lo, hi), edges in self.sections:
                if lo < d < hi:
                    return [Wire([Edge(e, d) for e in edges])]
            return []           # the plane misses the solid
        # a single fixture section stands for any plane within the shape's thickness
        bb = self.raw_bbox
        assert bb.YMin - 1e-9 <= d <= bb.YMax + 1e-9, "section plane Y=%g outside the shape" % d
        return [Wire([Edge(e, d) for e in self.section_edges])]

    def tessellate(self, tol):
        if self.mesh is None:
            return [], []
        v, t = self.mesh
        dy = self.Placement.Base.y
        return [Vector(p[0], p[1] + dy, p[2]) for p in v], [tuple(f) for f in t]


def makeCompound(shapes):
    edges = [e for s in shapes for e in s.section_edges]
    return Shape(edges, shapes[0].BoundBox, shapes[0].section_y)


# ---------------------------------------------------------------- pivy.coin
class Field:
    def __init__(self):
        self.values = []
        self.value = None

    def setNum(self, n):
        self.values = self.values[:n]

    def setValues(self, start, n, vals):
        vals = list(vals)
        assert len(vals) == n
        self.values = self.values[:start] + vals

    def setValue(self, *v):
        self.value = v


class Node:
    def __init__(self):
        object.__setattr__(self, "_fields", {})
        object.__setattr__(self, "children", [])

    def __getattr__(self, name):
        f = self._fields
        if name not in f:
            f[name] = Field()
        return f[name]

    def __setattr__(self, name, value):
        f = self.__getattr__(name)
        f.value = value

    def addChild(self, c):
        self.children.append(c)

    def removeChild(self, c):
        self.children.remove(c)

    def setName(self, n):
        self.name = n


def make_coin():
    coin = types.ModuleType("pivy.coin")
    for n in ("SoSeparator", "SoSwitch", "SoMaterial", "SoMaterialBinding", "SoCoordinate3",
              "SoIndexedFaceSet", "SoTransform", "SoDrawStyle", "SoLineSet", "SoBaseColor", "SoRotation"):
        setattr(coin, n, type(n, (Node,), {}))
    coin.SoShapeHints = type("SoShapeHints", (Node,), {"COUNTERCLOCKWISE": 1, "SOLID": 1, "UNKNOWN_ORDERING": 0})
    coin.SoLightModel = type("SoLightModel", (Node,), {"BASE_COLOR": 0})
    coin.SoMaterialBinding = type("SoMaterialBinding", (Node,), {"PER_VERTEX_INDEXED": 5, "PER_PART": 1})
    coin.SbVec3f = lambda *v: tuple(v)
    coin.SbRotation = lambda a, b: ("rotation", a, b)
    coin.SO_SWITCH_ALL = -3
    coin.SO_SWITCH_NONE = -1
    return coin


